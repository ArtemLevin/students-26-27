(() => {
  'use strict';

  const data = window.COMPETENCY_MAP_DATA;
  if (!data || !Array.isArray(data.groups)) return;

  const byId = new Map(
    data.groups.flatMap(group => (group.items || []).map(item => [item.id, item]))
  );

  // Диагностическая работа 06.09.26:
  // 4 — навык подтверждён самостоятельным верным выполнением;
  // 1 — в проверенном навыке выявлен пробел, тема добавляется в повторение;
  // 0 — навык этой диагностикой не проверялся.
  for (const item of byId.values()) {
    item.baselineLevel = 0;
  }

  const confirmed = [];
  const repeat = [];

  const setDiagnostic = (id, level, task, note) => {
    const item = byId.get(id);
    if (!item) return;
    item.baselineLevel = level;
    item.evidence = {
      date: '06.09.26',
      text: `Входная диагностика, задание №${task}: ${note}`
    };
    if (level >= 4) confirmed.push(id);
    if (level === 1) repeat.push(id);
  };

  // 1. Запись натурального числа цифрами — верно.
  setDiagnostic('nat_03', 4, 1, 'запись многозначного натурального числа цифрами выполнена верно.');

  // 2. Разрядные слагаемые — неверно.
  setDiagnostic('nat_05', 1, 2, 'вместо суммы разрядных слагаемых записаны цифры числа и названия разрядов.');

  // 3. Упорядочивание натуральных чисел — верно.
  setDiagnostic('nat_07', 4, 3, 'сравнение натуральных чисел по разрядам применено верно.');
  setDiagnostic('nat_08', 4, 3, 'числа правильно расположены по возрастанию.');

  // 4. Округление — не выполнено.
  setDiagnostic('nat_13', 1, 4, 'округление до сотен не выполнено.');
  setDiagnostic('nat_14', 1, 4, 'округление до тысяч не выполнено.');

  // 5. Четыре арифметических действия: +, × и : верно; вычитание — ошибка.
  setDiagnostic('arith_01', 4, '5.1', 'сложение многозначных натуральных чисел выполнено верно.');
  setDiagnostic('arith_02', 1, '5.2', 'в 9000−4685 неверно выполнено заимствование через нули.');
  setDiagnostic('arith_03', 4, '5.3', 'умножение многозначных натуральных чисел выполнено верно.');
  setDiagnostic('arith_04', 4, '5.4', 'деление многозначных натуральных чисел выполнено верно.');

  // 6. Порядок действий — потеряно умножение после скобок.
  setDiagnostic('arith_19', 1, 6, 'после вычисления скобок пропущено умножение 6·50.');
  setDiagnostic('arith_20', 1, 6, 'многошаговое выражение доведено до неверного результата из-за пропущенного действия.');

  // 7. Удобный способ вычисления — верно.
  setDiagnostic('arith_13', 4, 7, 'переместительное свойство умножения использовано корректно.');
  setDiagnostic('arith_14', 4, 7, 'сочетательное свойство умножения использовано корректно.');
  setDiagnostic('arith_16', 4, 7, 'множители сгруппированы удобным способом, результат верный.');

  // 8. Деление с остатком и проверка — верно.
  setDiagnostic('div_13', 4, 8, 'деление с остатком выполнено верно.');
  setDiagnostic('div_14', 4, 8, 'частное и остаток корректно проверены через связь компонентов деления.');

  // 9. Признаки делимости — верно.
  setDiagnostic('div_07', 4, '9.1', 'признак делимости на 2 применён верно.');
  setDiagnostic('div_08', 4, '9.2', 'признак делимости на 5 применён верно.');
  setDiagnostic('div_10', 4, '9.4', 'признак делимости на 3 применён верно.');
  setDiagnostic('div_11', 4, '9.3', 'признак делимости на 9 применён верно.');
  setDiagnostic('div_12', 4, '9.4', 'условие «делится на 3, но не делится на 9» обработано верно.');

  // 10. Простые и составные числа — не выполнено.
  setDiagnostic('div_06', 1, 10, 'классификация чисел на простые и составные не выполнена.');

  // 11. Смешанное число ↔ неправильная дробь — не выполнено.
  setDiagnostic('frac_base_06', 1, '11.1', 'перевод смешанного числа в неправильную дробь не выполнен.');
  setDiagnostic('frac_base_07', 1, '11.2', 'выделение целой части из неправильной дроби не выполнено.');

  // 12. Сокращение и сравнение дробей — не выполнено.
  setDiagnostic('frac_base_11', 1, '12.1', 'сокращение дроби не выполнено.');
  setDiagnostic('frac_base_15', 1, '12.2', 'сравнение дробей с разными знаменателями не выполнено.');

  // 13. Сложение и вычитание дробей с разными знаменателями — не выполнено.
  setDiagnostic('frac_ops_03', 1, '13.1', 'сложение дробей с разными знаменателями не выполнено.');
  setDiagnostic('frac_ops_04', 1, '13.2', 'вычитание дробей с разными знаменателями не выполнено.');

  // 14. Сравнение десятичных дробей — ошибка.
  setDiagnostic('dec_07', 1, 14, 'числа расположены не по возрастанию; 0,9 ошибочно поставлено перед 0,09.');

  // 15. Сложение десятичных дробей — верно; вычитание — ошибка.
  setDiagnostic('dec_09', 4, '15.1', 'сложение десятичных дробей выполнено верно.');
  setDiagnostic('dec_10', 1, '15.2', 'изменён порядок вычитания и число 40 фактически заменено на 4,000.');

  // 16. Умножение десятичных дробей — верно; деление на десятичную дробь — не выполнено.
  setDiagnostic('dec_12', 4, '16.1', 'умножение десятичных дробей выполнено верно.');
  setDiagnostic('dec_14', 1, '16.2', 'деление десятичной дроби на десятичную дробь не выполнено.');

  // 17. Двухшаговое уравнение и проверка — верно.
  setDiagnostic('eq_06', 4, 17, 'неизвестный множитель найден верно.');
  setDiagnostic('eq_03', 4, 17, 'неизвестное слагаемое найдено верно.');
  setDiagnostic('eq_09', 4, 17, 'выполнена корректная проверка подстановкой.');

  // 18. Задача на цену, количество и стоимость — верно.
  setDiagnostic('word_10', 4, 18, 'зависимость «цена–количество–стоимость» использована верно.');
  setDiagnostic('word_11', 4, 18, 'стоимость 13 тетрадей найдена верно.');
  setDiagnostic('word_12', 4, 18, 'цена одной тетради корректно найдена по общей стоимости и количеству.');

  // 19. Формула пути записана верно, но задача не доведена до ответа.
  setDiagnostic('eq_13', 4, 19, 'формула пути S=v·t выбрана и записана верно.');
  setDiagnostic('word_06', 1, 19, 'задача на скорость, время и расстояние не завершена.');
  setDiagnostic('word_07', 1, 19, 'расстояние по скорости и времени не вычислено.');

  // 20. Перевод единиц: длина и время — верно; масса — ошибка.
  setDiagnostic('units_01', 4, '20.1', 'километры переведены в метры верно.');
  setDiagnostic('units_03', 4, '20.2', 'часы и минуты переведены в минуты верно.');
  setDiagnostic('units_02', 1, '20.3', '4500 г ошибочно переведены в 45 кг вместо 4,5 кг.');

  // 21. Периметр и площадь прямоугольника — верно.
  setDiagnostic('area_02', 4, 21, 'периметр прямоугольника найден верно.');
  setDiagnostic('area_06', 4, 21, 'площадь прямоугольника найдена верно.');

  // 22. Вид угла и объём прямоугольного параллелепипеда — неверно/не выполнено.
  setDiagnostic('angles_03', 1, '22.1', 'угол 127° ошибочно отнесён к острым.');
  setDiagnostic('angles_04', 1, '22.1', 'не распознано, что угол 127° является тупым.');
  setDiagnostic('solid_08', 1, '22.2', 'объём прямоугольного параллелепипеда не найден.');

  data.repeatTopics = [...new Set(repeat)];
  data.meta.updated = '06.09.2026';
  data.meta.sourceNote = 'Карта обновлена по входной диагностической работе 06.09.26. Уровень 4 — навык подтверждён самостоятельным верным выполнением; уровень 1 — выявлен пробел и тема добавлена в повторение; уровень 0 — этой диагностикой навык не проверялся.';

  const slug = value => String(value).toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^a-z0-9а-я]+/gi, '-')
    .replace(/^-+|-+$/g, '');

  // Новый маркер сбрасывает старое локальное состояние один раз,
  // чтобы результаты диагностики 06.09.26 стали новой подтверждённой базой.
  const markerKey = `${data.meta.student}-competency-map-diagnostic-20260906-v1`;
  try {
    if (!localStorage.getItem(markerKey)) {
      const baseKey = `${data.meta.student}-${slug(data.meta.program)}`;
      localStorage.removeItem(`${baseKey}-competency-map`);
      localStorage.removeItem(`${baseKey}-repeat`);
      localStorage.setItem(markerKey, '1');
    }
  } catch (_) {}
})();